import assert from "node:assert/strict";
import { currentDirection,currentPlaneLinked,setCurrentDirection,setCurrentPosition,moveCurrentCorner } from "../js/current-plane.js";
import { resolveTemplate } from "../js/params.js";
const cube={type:"current",start:[-5,-5,0],stop:[5,5,10]};
assert.equal(currentDirection(cube),"z");
assert.equal(currentPlaneLinked(cube),false);
setCurrentDirection(cube,"z");
assert.deepEqual(cube.stop,[5,5,0]);
assert.equal(currentPlaneLinked(cube),true);
setCurrentPosition(cube,5);
assert.deepEqual(cube.start,[-5,-5,5]);
assert.deepEqual(cube.stop,[5,5,5]);
moveCurrentCorner(cube,"start",[-4,-3,0],[true,true,true]);
assert.deepEqual(cube.start,[-4,-3,0]);
assert.deepEqual(cube.stop,[5,5,0]);
moveCurrentCorner(cube,"stop",[-8,5,2],[true,true,true]);
assert.deepEqual(cube.stop,[5,5,2]);
assert.equal(cube.start[2],2);
setCurrentDirection(cube,"-x");
assert.equal(cube.direction,"-x");
assert.deepEqual(cube.start,[-4,-3,2]);
assert.deepEqual(cube.stop,[-4,5,11]);
const plane={start:[0,1,{$param:"z"}],stop:[5,6,{$param:"z"}]};
assert.equal(currentDirection(plane),"z");
moveCurrentCorner(plane,"stop",[5,6,7],[true,true,true]);
assert.deepEqual(plane.stop[2],{$param:"z"});
setCurrentDirection(plane,"y");
assert.equal(currentPlaneLinked(plane),true);
assert.deepEqual(resolveTemplate(plane.stop,{z:3}),[5,1,8]);
setCurrentPosition(plane,{$expr:"z+2"});
assert.deepEqual(plane.start[1],plane.stop[1]);
assert.notEqual(plane.start[1],plane.stop[1]);
console.log("Current-plane editor tests passed");
