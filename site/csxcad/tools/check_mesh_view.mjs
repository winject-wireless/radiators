import assert from "node:assert/strict";
import {meshSegments,meshMinima,nearestLine,validMeshLines} from "../js/sim/mesh-view.js";
import {buildModel} from "../js/sim/model.js";
import {STARTER} from "../js/schema.js";
import {resolveCase,parameterSets} from "../js/params.js";
const lines=[[-10,0,.025,10],[-20,0,20],[-30,-1,0,30]];
assert.equal(validMeshLines(lines),true);
assert.equal(validMeshLines([[0,1],[0,0],[0,1]]),false);
assert.equal(nearestLine(lines[0],.02),2);
assert.deepEqual(meshMinima(lines)[0],{axis:0,index:1,min:.025,start:0,stop:.025});
const xz=meshSegments(lines,{plane:"XZ",index:1});
assert.equal(xz.position,0);
const all=[...xz.regular,...xz.smallest,...xz.absorbing];
assert.equal(all.length/6,8);
assert.ok(all.every((v,i)=>i%3!==1||v===0));
assert.ok(xz.smallest.some((v,i)=>i%3===0&&v===.025));
const xy=meshSegments(lines,{plane:"XY",index:1,highlight:false,pml:true,boundary:["PML_1","PML_1","PML_1","PML_1","PEC","PEC"]});
assert.equal(xy.position,-1);
assert.ok(xy.absorbing.length>0);assert.equal(xy.smallest.length,0);
const dense=Array.from({length:3},()=>Array.from({length:500},(_,i)=>i));
const volume=meshSegments(dense,{plane:"3D",max3D:12});
assert.ok(volume.decimated);
assert.ok((volume.regular.length+volume.smallest.length+volume.absorbing.length)/6<1000);
const cfg=resolveCase(STARTER,parameterSets(STARTER)[0].parameters);
const full=buildModel(cfg),preview=buildModel(cfg,{meshOnly:true});
assert.deepEqual(preview.meshLines,full.meshLines);
assert.deepEqual(preview.counts,full.counts);
assert.equal(preview.cells,full.cells);
assert.deepEqual(buildModel({...cfg,probes:[{name:"bad",type:"current",start:[-1,-1,-1],stop:[1,1,1]}]},{meshOnly:true}).meshLines,preview.meshLines);
console.log("Mesh view geometry and exact preview parity: PASS");
