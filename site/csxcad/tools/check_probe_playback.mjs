import assert from "node:assert/strict";
import { diagnosticFrame, sampleTime, nearestTime } from "../js/sim/probe-playback.js";
assert.deepEqual(sampleTime([0,1],[[0],[4]],.25),[1]);
assert.equal(sampleTime([0,1],[[0],[4]],-1),null);
assert.equal(nearestTime([0,1,2],1.7),2);
const scalar=(id,amplitude,sign=1)=>({id,name:id,type:"current",axis:2,sign,components:1,unit:"A",start:[0,-2,5],stop:[0,2,5],time_s:[0,1],values:[[amplitude],[-amplitude]]});
const arrows=diagnosticFrame([scalar("drive",2),scalar("reflector",.5)],{time:1,scale:10});
assert.deepEqual(arrows[0].position,[0,0,5]);
assert.deepEqual(arrows[0].vector,[0,0,-10]);
assert.deepEqual(arrows[1].vector,[0,0,-2.5]);
assert.match(arrows[1].label,/-0.5000 A/);
assert.equal(diagnosticFrame([scalar("reverse",2,-1)],{time:0})[0].vector[2],-1);
const b64=a=>{const b=Buffer.alloc(a.length*4);a.forEach((x,i)=>b.writeFloatLE(x,i*4));return b.toString("base64");};
const field={id:"field",type:"field_dump",field:"E",unit:"V/m",td:{axes_mm:[[5],[6,7],[8]],time_s:[0,1],peak:4,frames_f32:b64([1,0,0,0,2,0,-4,0,0,0,-2,0])}};
const vectors=diagnosticFrame([field],{time:1,scale:8});
assert.deepEqual(vectors[0].position,[5,6,8]);
assert.deepEqual(vectors[0].vector,[-8,0,0]);
assert.deepEqual(vectors[1].position,[5,7,8]);
assert.deepEqual(vectors[1].vector,[0,-4,0]);
const fd={...field,td:null,fd:{axes_mm:[[5],[6],[8]],frequency_hz:[2450000000],peak:2,real_f32:b64([0,0,0]),imag_f32:b64([0,2,0])}};
const ph=diagnosticFrame([fd],{mode:"fd",frequency:2450000000,phase:90,scale:8});
assert.ok(Math.abs(ph[0].vector[1]+8)<1e-9);
console.log("Diagnostic playback tests passed");
